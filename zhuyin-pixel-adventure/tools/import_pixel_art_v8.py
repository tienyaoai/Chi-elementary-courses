#!/usr/bin/env python3
"""Import v8 512 PNGs -> 256 nearest-neighbor into static/pixel-art/ and emit manifest.rs."""
from __future__ import annotations

import json
import shutil
import sys
import zipfile
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
OUT_DIR = ROOT / "static" / "pixel-art"
OUT_RS = ROOT / "src" / "pixel_art_manifest.rs"
SIZE = 256

SKIP_PROMPT = "三張選項圖"


def main() -> None:
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(
        "/home/ubuntu/.cursor/projects/workspace/uploads/pixel-art-v8_a246.zip"
    )
    if OUT_DIR.exists():
        shutil.rmtree(OUT_DIR)
    OUT_DIR.mkdir(parents=True)

    with zipfile.ZipFile(src) as zf:
        manifest = json.loads(zf.read("pixel-art-v8/manifest.json"))
        for desc, fname in manifest.items():
            raw = zf.read(f"pixel-art-v8/{fname}")
            im = Image.open(__import__("io").BytesIO(raw)).convert("RGBA")
            im = im.resize((SIZE, SIZE), Image.Resampling.NEAREST)
            im.save(OUT_DIR / fname, optimize=True)
        gallery_bytes = zf.read("pixel-art-v8/gallery.png")
        (Path("/opt/cursor/artifacts")).mkdir(parents=True, exist_ok=True)
        Path("/opt/cursor/artifacts/learning-adventure-pixel-art-gallery-v8.png").write_bytes(
            gallery_bytes
        )

    (OUT_DIR / "manifest.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8"
    )

    items = sorted(manifest.items(), key=lambda x: x[0])
    lines = [
        "// @generated by tools/import_pixel_art_v8.py",
        "",
        "pub const SKIP_PROMPT_IMAGES: &[&str] = &[\"三張選項圖\"];",
        "",
        "pub static MANIFEST: &[(&str, &str)] = &[",
    ]
    for desc, fname in items:
        lines.append(f'    ("{desc}", "{fname}"),')
    lines += [
        "];",
        "",
        "pub fn file_for(desc: &str) -> Option<&'static str> {",
        "    MANIFEST.binary_search_by(|e| e.0.cmp(desc)).ok().map(|i| MANIFEST[i].1)",
        "}",
        "",
        "pub fn image_url(desc: &str) -> Option<String> {",
        "    file_for(desc).map(|f| format!(\"/pixel-art/{f}\"))",
        "}",
        "",
        "pub fn art_supported(desc: &str) -> bool {",
        "    if SKIP_PROMPT_IMAGES.contains(&desc) {",
        "        return true;",
        "    }",
        "    file_for(desc).is_some()",
        "}",
        "",
    ]
    OUT_RS.write_text("\n".join(lines), encoding="utf-8")

    total = sum(f.stat().st_size for f in OUT_DIR.iterdir() if f.suffix == ".png")
    print(f"Wrote {len(items)} images ({SIZE}px) -> {OUT_DIR}")
    print(f"Total PNG size: {total / 1024 / 1024:.2f} MiB")
    print(f"Manifest -> {OUT_RS}")


if __name__ == "__main__":
    main()
